from PySide6.QtWidgets import QWidget, QVBoxLayout, QHBoxLayout, QLabel, QPushButton
from .widgets import Panel, MetricPanel
from .camera_view import CameraView
from .status_panel import StatusPanel

class Dashboard(QWidget):
    def __init__(self):
        super().__init__()
        outer = QVBoxLayout(self)
        outer.setContentsMargins(26,22,26,22)
        heading = QHBoxLayout()
        title = QLabel("Live operations")
        title.setStyleSheet("font-size:27px;font-weight:750;")
        heading.addWidget(title)
        heading.addStretch()
        self.start_button = QPushButton("Start monitoring")
        self.start_button.setObjectName("primary")
        self.stop_button = QPushButton("Stop monitoring")
        heading.addWidget(self.start_button)
        heading.addWidget(self.stop_button)
        outer.addLayout(heading)
        sub = QLabel("Continuous pose tracking · Experimental movement analysis")
        sub.setObjectName("muted")
        outer.addWidget(sub)
        content = QHBoxLayout()
        content.setSpacing(16)
        left = QVBoxLayout()
        self.camera = CameraView()
        camera_panel = Panel()
        camera_panel.layout.addWidget(QLabel("CAMERA FEED  /  SKELETON OVERLAY", objectName="eyebrow"))
        camera_panel.layout.addWidget(self.camera, 1)
        left.addWidget(camera_panel, 1)
        metrics = QHBoxLayout()
        self.fps = MetricPanel("Render FPS", "—", "Camera stream")
        self.pose = MetricPanel("Pose engine", "READY", "MediaPipe")
        self.movement = MetricPanel("Movement", "Waiting", "Live classification")
        metrics.addWidget(self.fps)
        metrics.addWidget(self.pose)
        metrics.addWidget(self.movement)
        left.addLayout(metrics)
        content.addLayout(left, 3)
        right = QVBoxLayout()
        self.status = StatusPanel()
        right.addWidget(self.status)
        info = Panel()
        info.layout.addWidget(QLabel("SYSTEM INTEGRITY", objectName="eyebrow"))
        self.camera_status = QLabel("Camera: standby")
        self.arduino_status = QLabel("Arduino: not connected")
        self.demo_status = QLabel("Hospital link: SIMULATED")
        for item in (self.camera_status,self.arduino_status,self.demo_status):
            item.setObjectName("muted")
            info.layout.addWidget(item)
        right.addWidget(info)
        note = QLabel("This prototype is not medically validated and does not contact emergency services.")
        note.setWordWrap(True)
        note.setObjectName("muted")
        right.addWidget(note)
        right.addStretch()
        content.addLayout(right, 1)
        outer.addLayout(content, 1)
